using System.Text;
using System.Text.Json;
using Acta.Relational.Resources;
using Acta.Relational.Schema;

namespace Acta.Emit.Features.Docs;

/// <summary>
/// Emits <c>docs/reference/provision/{dialect}.sql</c>: one provider's complete provisioning script,
/// composed from the same on-disk SQL the provider embeds (migration history table, every migration
/// in order, operator views, routines) and fully rendered for the default schema, so a DBA can
/// review and run it verbatim. Exists because locked-down deployments forbid DDL from the
/// application principal: the pipeline runs this file under an elevated one, the application keeps
/// <c>ApplyMigrationsOnStartup = false</c>, and because each migration records its own history row
/// (including the baseline stamp) the bootstrap accepts the result as its own work.
/// </summary>
internal static class ProvisionScriptEmitter
{
    internal static readonly (string Token, string Project, string Schema)[] Providers =
    [
        ("pg", "Acta.Postgres", "acta"),
        ("mssql", "Acta.SqlServer", "acta"),
        ("sqlite", "Acta.Sqlite", "main"),
    ];

    internal static string Emit(string repoRoot, string token)
    {
        var (_, project, schema) = Providers.Single(p => string.Equals(p.Token, token, StringComparison.Ordinal));
        var providerDir = Path.Combine(repoRoot, "src", project);
        var mssql = string.Equals(token, "mssql", StringComparison.Ordinal);

        var script = new StringBuilder();
        script.AppendLine($"-- Acta full provisioning script ({token}), schema '{schema}'. GENERATED by tools/Acta.Emit (`docs`");
        script.AppendLine("-- command); do not hand-edit here - edit the source SQL and regenerate. To relocate, replace the");
        script.AppendLine($"-- schema name '{schema}' throughout. Baseline stamp: {SchemaMigrationRunner.RequiredBaselineStamp}.");
        script.AppendLine("--");
        script.AppendLine("-- The same SQL the bootstrap migration runner applies: the migration history table, every");
        script.AppendLine("-- migration in order (each records its own history row), then operator views and routines.");
        script.AppendLine("-- Idempotent. Run it under a DDL-capable principal; the application principal then needs only");
        script.AppendLine("-- DML and EXECUTE, with ApplyMigrationsOnStartup left false. Because the history rows (and the");
        script.AppendLine("-- baseline stamp) are recorded by the script itself, a bootstrap with migrations enabled also");
        script.AppendLine("-- accepts the result and applies nothing. Site-specific physical tuning (partitioning,");
        script.AppendLine("-- tablespaces, compression) is yours to add; keep the logical shape - tables, columns,");
        script.AppendLine("-- constraints, routine signatures - intact.");
        script.AppendLine();

        void Append(string text)
        {
            script.AppendLine(text.TrimEnd());
            script.AppendLine(mssql ? "GO" : "");
        }

        string Render(string sql)
        {
            if (sql.Contains("{{table", StringComparison.Ordinal))
            {
                throw new InvalidOperationException("Provision scripts never include outbox source-catalog templates.");
            }
            return CodeDecodeSql.RenderDecodeTokens(
                sql.Replace("{{schema}}", schema).Replace("{{now}}", "CAST(unixepoch('now', 'subsec') * 1000 AS INTEGER)")
            );
        }

        if (mssql)
        {
            // Mirrors the runner's prelude: M001 has filtered indexes that require these session options.
            Append("SET QUOTED_IDENTIFIER ON;\nSET ANSI_NULLS ON;");
        }
        Append(mssql ? "SET XACT_ABORT ON;\nBEGIN TRANSACTION;" : "BEGIN;");
        Append(Render(File.ReadAllText(Path.Combine(providerDir, "Sql", "Schema", "EnsureMigrations.sql"))));

        var migrationsDir = Path.Combine(providerDir, "Schema", "Migrations");
        foreach (var migration in Directory.GetFiles(migrationsDir, "M*.sql").OrderBy(f => f, StringComparer.Ordinal))
        {
            Append(Render(File.ReadAllText(migration)));
        }

        // Views before routines, each set in resource-name order, mirroring SqlObjectInstaller.
        foreach (var (name, body) in SqlObjects(providerDir, ".view.sql"))
        {
            if (!name.EndsWith("_view", StringComparison.Ordinal))
            {
                throw new InvalidOperationException($"Provider view '{name}' must install as a plural '_view' name.");
            }
            var qualified = $"{schema}.{name}";
            var select = Render(body).Trim();
            Append(
                mssql
                    ? $"CREATE OR ALTER VIEW {qualified} AS\n{select}"
                    : $"DROP VIEW IF EXISTS {qualified};\nCREATE VIEW {qualified} AS\n{select};"
            );
        }
        foreach (var (_, body) in SqlObjects(providerDir, ".routine.sql"))
        {
            Append(Render(body));
        }

        Append(mssql ? "COMMIT TRANSACTION;" : "COMMIT;");
        return script.ToString().ReplaceLineEndings("\n");
    }

    private static IEnumerable<(string Name, string Body)> SqlObjects(string providerDir, string suffix) =>
        Directory
            .EnumerateFiles(Path.Combine(providerDir, "Sql"), "*" + suffix, SearchOption.AllDirectories)
            .Select(path => (Path: path, Resource: Path.GetRelativePath(providerDir, path).Replace('\\', '.').Replace('/', '.')))
            .OrderBy(f => f.Resource, StringComparer.Ordinal)
            .Select(f =>
                (JsonNamingPolicy.SnakeCaseLower.ConvertName(Path.GetFileName(f.Path)[..^suffix.Length]), File.ReadAllText(f.Path))
            );
}
