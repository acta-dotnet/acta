using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using static Acta.Generators.ActaManifestGenerator;

namespace Acta.Generators;

/// <summary>Writes the manifest source: the descriptors, the job contracts, and the generated handler dispatch.</summary>
internal static class ManifestSourceWriter
{
    /// <summary>
    /// Manifest type name = the assembly's area (RootNamespace's last segment). Non-"Jobs" areas get
    /// the short "{Area}Jobs" (e.g. "HelloActa" to "HelloActaJobs"). An area already ending in "Jobs"
    /// keeps a "Manifest" suffix ("TestJobs" to "TestJobsManifest", "Jobs" to "JobsManifest") because
    /// "{Area}" alone would equal the type's own namespace segment and the namespace would shadow it.
    /// </summary>
    internal static string ManifestTypeName(string rootNamespace)
    {
        var dot = rootNamespace.LastIndexOf('.');
        var segment = dot < 0 ? rootNamespace : rootNamespace.Substring(dot + 1);
        return segment.EndsWith("Jobs", StringComparison.Ordinal) ? segment + "Manifest" : segment + "Jobs";
    }

    /// <summary>The argument record of a job taking several parameters, unless its generated names collide.</summary>
    internal static string ArgumentsName(DiscoveredJob j) => PascalCase(j.JobName) + "Args";

    internal static string BuildManifestSource(
        string rootNamespace,
        string manifestTypeName,
        DiscoveredJob[] jobs,
        IReadOnlyDictionary<string, byte> customFormatById,
        ISet<string> contractCollisions
    )
    {
        var namespaceName = string.Join(".", rootNamespace.Split('.').Select(GeneratorText.EscapeIdentifier));

        // A job whose generated names collide names its argument record by its dispatch suffix, which no member name
        // can match, since a member name has no underscore.
        jobs = [.. jobs];
        var argumentRecords = new List<(DiscoveredJob Job, string Name)>();
        for (var i = 0; i < jobs.Length; i++)
        {
            if (jobs[i].TakesArguments)
            {
                var name = contractCollisions.Contains(jobs[i].JobName) ? $"Args_{jobs[i].DispatchSuffix(i)}" : ArgumentsName(jobs[i]);
                jobs[i] = jobs[i] with { ArgumentsTypeName = $"global::{namespaceName}.{manifestTypeName}.{name}" };
                argumentRecords.Add((jobs[i], name));
            }
        }

        var sb = new StringBuilder();
        // The file has no usings and names every type global-qualified: a call member named like
        // a type (job `immutable-array` is member `ImmutableArray`), or an application type of the
        // same name in the root namespace, would otherwise hide it.
        GeneratorText.AutoGeneratedHeader(sb);
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Generator-emitted manifest for this assembly. Bound to a namespace at registration");
        sb.AppendLine($"/// time via <c>IActaBuilder.Run&lt;{manifestTypeName}&gt;(namespaceName)</c>.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public sealed class {manifestTypeName} : global::Acta.IJobManifest");
        sb.AppendLine("{");
        sb.AppendLine("    public static global::Acta.JobDescriptorManifest Descriptors { get; } =");
        sb.AppendLine("        new global::Acta.JobDescriptorManifest(");
        sb.AppendLine("            Descriptors: global::System.Collections.Immutable.ImmutableArray.Create<global::Acta.JobDescriptor>(");
        var dispatch = $"global::{namespaceName}.GeneratedHandlerDispatch";
        for (var i = 0; i < jobs.Length; i++)
        {
            EmitDescriptor(sb, jobs[i], dispatch, jobs[i].DispatchSuffix(i), i == jobs.Length - 1 ? "" : ",", customFormatById);
        }
        sb.AppendLine("            ));");
        EmitCalls(sb, jobs, manifestTypeName, contractCollisions);
        foreach (var (job, name) in argumentRecords)
        {
            var parameters = job.InputParameters.Select(p => $"{ArgumentTypeName(p.Type)} {GeneratorText.EscapeIdentifier(p.Name)}");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine(
                $"    /// Input of job <c>{job.JobName}</c>: its handler's input parameters, serialized as one object whose property"
            );
            sb.AppendLine("    /// names are part of the job's contract.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    public sealed record {name}({string.Join(", ", parameters)});");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        EmitGeneratedHandlerDispatchClass(sb, jobs);
        return sb.ToString();
    }

    /// <summary>One <c>JobDescriptor</c> of the manifest, followed by <paramref name="trailing"/>.</summary>
    private static void EmitDescriptor(
        StringBuilder sb,
        DiscoveredJob j,
        string dispatch,
        string dispatchSuffix,
        string trailing,
        IReadOnlyDictionary<string, byte> customFormatById
    )
    {
        sb.AppendLine($"                new global::Acta.JobDescriptor(");
        sb.AppendLine($"                    JobName: \"{j.JobName}\",");
        sb.AppendLine($"                    HandlerType: typeof({DisplayName(j.HandlerType!)}),");
        sb.AppendLine($"                    MethodName: \"{j.MethodName}\",");
        sb.AppendLine($"                    InputType: typeof({InputTypeExpr(j)}),");
        var outputTypeExpr = j.OutputType is null ? "null" : $"typeof({DisplayName(j.OutputType)})";
        sb.AppendLine($"                    OutputType: {outputTypeExpr},");
        sb.AppendLine($"                    InputPayloadFormat: {PayloadFormatExpression(j.InputPayloadFormatName, customFormatById)},");
        var outputFormatExpr = j.OutputPayloadFormatName is null
            ? "null"
            : PayloadFormatExpression(j.OutputPayloadFormatName, customFormatById);
        sb.AppendLine($"                    OutputPayloadFormat: {outputFormatExpr},");
        sb.AppendLine($"                    Priority: global::Acta.JobPriorityCode.{j.PriorityName},");
        sb.AppendLine($"                    MaxAttempts: {j.MaxAttempts},");
        sb.AppendLine($"                    EventRecording: global::Acta.EventRecordingCode.{j.EventRecordingName},");
        sb.AppendLine($"                    AlertProfile: global::Acta.AlertProfileCode.{j.AlertProfileName},");
        sb.AppendLine($"                    FiringFailurePolicy: global::Acta.FiringFailurePolicyCode.{j.FiringFailurePolicyName},");
        sb.AppendLine($"                    ScheduledDelivery: global::Acta.ScheduledDeliveryCode.{j.ScheduledDeliveryName},");
        sb.AppendLine($"                    Invoker: {dispatch}.Invoke_{dispatchSuffix},");
        sb.AppendLine($"                    DeserializeInput: {dispatch}.DeserializeInput_{dispatchSuffix},");
        var serExpr = j.OutputType is null ? "null" : $"{dispatch}.SerializeOutput_{dispatchSuffix}";

        var policyLines = PolicyLines(j);

        var hasSchedules = !j.Schedules.IsDefaultOrEmpty;
        if (policyLines.Count == 0 && !hasSchedules)
        {
            sb.AppendLine($"                    SerializeOutput: {serExpr}){trailing}");
        }
        else
        {
            sb.AppendLine($"                    SerializeOutput: {serExpr})");
            sb.AppendLine("                {");
            foreach (var line in policyLines)
            {
                sb.AppendLine($"                    {line}");
            }
            if (hasSchedules)
            {
                sb.AppendLine(
                    "                    Schedules = global::System.Collections.Immutable.ImmutableArray.Create<global::Acta.ScheduleDescriptor>("
                );
                EmitScheduleDescriptors(sb, j);
                sb.AppendLine("                    ),");
                // A none-format slot seeds an empty payload; the registrar never asks it for a default input.
                if (j.InputPayloadFormatName != "none")
                {
                    sb.AppendLine($"                    CreateDefaultInput = static () => new {InputTypeExpr(j)}(),");
                    sb.AppendLine($"                    SerializeInput = {dispatch}.SerializeInput_{dispatchSuffix},");
                }
            }
            sb.AppendLine($"                }}{trailing}");
        }
    }

    /// <summary>The descriptor's init lines for every policy the attribute set away from its default.</summary>
    private static List<string> PolicyLines(DiscoveredJob j)
    {
        var policyLines = new List<string>();
        if (j.TenantRequirementId != 0)
        {
            policyLines.Add($"TenantRequirement = (global::Acta.DefinitionTenantRequirementCode){j.TenantRequirementId},");
        }

        if (j.ConcurrencyLimit is { } concurrencyLimit)
        {
            policyLines.Add($"ConcurrencyLimit = {concurrencyLimit},");
        }

        if (j.RateLimit is { } rateLimitRaw)
        {
            policyLines.Add($"RateLimit = {FormatString(rateLimitRaw)},");
        }

        if (j.RateName is { } rateNameRaw)
        {
            policyLines.Add($"RateName = {FormatString(rateNameRaw)},");
        }

        if (j.Lane is { } laneRaw)
        {
            policyLines.Add($"Lane = {FormatString(laneRaw)},");
        }

        if (j.Backoff is { } backoffRaw)
        {
            policyLines.Add($"Backoff = {FormatString(backoffRaw)},");
        }

        if (j.ExecutionTimeoutSeconds is { } timeout)
        {
            policyLines.Add($"ExecutionTimeoutSeconds = {timeout},");
        }

        if (j.DeadlineSeconds is { } deadline)
        {
            policyLines.Add($"DeadlineSeconds = {deadline},");
        }

        if (j.DeadlineBehaviorId != 10)
        {
            policyLines.Add($"DeadlineBehavior = (global::Acta.DeadlineBehaviorCode){j.DeadlineBehaviorId},");
        }

        if (j.JobRetentionSeconds is { } retention)
        {
            policyLines.Add($"JobRetentionSeconds = {retention},");
        }

        if (j.AlertChannelName is { } channel)
        {
            policyLines.Add($"AlertChannelName = {FormatString(channel)},");
        }

        if (j.RunbookUrl is { } runbook)
        {
            policyLines.Add($"RunbookUrl = {FormatString(runbook)},");
        }

        if (j.DisplayName is { } displayName)
        {
            policyLines.Add($"DisplayName = {FormatString(displayName)},");
        }

        if (j.Description is { } description)
        {
            policyLines.Add($"Description = {FormatString(description)},");
        }

        if (j.InputTemplateJson is { } inputTemplate)
        {
            policyLines.Add($"InputTemplateJson = {FormatString(inputTemplate)},");
        }
        return policyLines;
    }

    /// <summary>
    /// One factory per job, taking the handler's input parameters and returning the job's call: its contract with the
    /// input they make. An input that carries no data is fabricated, as dispatch does.
    /// </summary>
    internal static void EmitCalls(StringBuilder sb, DiscoveredJob[] jobs, string manifestTypeName, ISet<string> contractCollisions)
    {
        foreach (var j in jobs.Where(j => !contractCollisions.Contains(j.JobName)))
        {
            var input = InputTypeExpr(j);
            var types = j.OutputType is null ? input : $"{input}, {DisplayName(j.OutputType)}";
            var names = j.InputParameters.Select(p => GeneratorText.EscapeIdentifier(p.Name)).ToArray();
            var (parameters, value) =
                j.TakesArguments
                    ? (
                        string.Join(", ", j.InputParameters.Select((p, k) => $"{ArgumentTypeName(p.Type)} {names[k]}")),
                        $"new {input}({string.Join(", ", names)})"
                    )
                : j.InputPayloadFormatName == "none" ? ("", $"new {input}()")
                : ($"{input} {names[0]}", names[0]);

            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine(
                $"    /// Call of job <c>{j.JobName}</c>, for <c>IJobs.EnqueueAsync</c>, <c>ScheduleAsync</c>, and <c>RunAndWaitAsync</c>."
            );
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    public static global::Acta.JobCall<{types}> {PascalCase(j.JobName)}({parameters}) =>");
            sb.AppendLine($"        new(new global::Acta.JobContract<{types}>(typeof({manifestTypeName}), \"{j.JobName}\"), {value});");
        }
    }

    internal static string FormatString(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    internal static void EmitScheduleDescriptors(StringBuilder sb, DiscoveredJob j)
    {
        for (var i = 0; i < j.Schedules.Length; i++)
        {
            var s = j.Schedules[i];
            var trailing = i == j.Schedules.Length - 1 ? "" : ",";
            var envExpr = s.Environments.IsDefaultOrEmpty
                ? "global::System.Collections.Immutable.ImmutableArray<string>.Empty"
                : $"global::System.Collections.Immutable.ImmutableArray.Create<string>({string.Join(", ", s.Environments.Select(FormatString))})";
            sb.AppendLine("                        new global::Acta.ScheduleDescriptor(");
            sb.AppendLine($"                            JobName: {FormatString(s.JobName)},");
            sb.AppendLine($"                            ScheduleName: {FormatString(s.ScheduleName)},");
            sb.AppendLine($"                            Expression: {FormatString(s.Expression)},");
            sb.AppendLine($"                            TimeZoneId: {LitOrNull(s.TimeZoneId)},");
            sb.AppendLine(
                $"                            MisfireStrategy: global::Acta.MisfireStrategyCode.{JobPolicyValues.MisfireStrategyIdToName(s.MisfireStrategyId)},"
            );
            sb.AppendLine($"                            ExpressionKind: global::Acta.ScheduleExpressionKindCode.{s.ExpressionKindName},");
            sb.AppendLine($"                            Description: {LitOrNull(s.Description)},");
            sb.AppendLine($"                            Environments: {envExpr},");
            sb.AppendLine($"                            MaxOutstanding: {s.MaxOutstanding},");
            sb.AppendLine(
                $"                            FullBehavior: global::Acta.ScheduleFullBehaviorCode.{JobPolicyValues.ScheduleFullBehaviorIdToName(s.FullBehaviorId)},"
            );
            sb.AppendLine(
                $"                            ExpireAfterSeconds: {s.ExpireAfterSeconds?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "null"},"
            );
            sb.AppendLine(
                $"                            ExpireAction: global::Acta.ScheduleExpireActionCode.{JobPolicyValues.ScheduleExpireActionIdToName(s.ExpireActionId) ?? "Unspecified"}){trailing}"
            );
        }
    }

    internal static string LitOrNull(string? value) => value is null ? "null" : FormatString(value);

    internal static void EmitGeneratedHandlerDispatchClass(StringBuilder sb, DiscoveredJob[] jobs)
    {
        sb.AppendLine("file static class GeneratedHandlerDispatch");
        sb.AppendLine("{");
        for (var i = 0; i < jobs.Length; i++)
        {
            var j = jobs[i];
            var suffix = j.DispatchSuffix(i);
            var inputTypeName = InputTypeExpr(j);
            // "none" format means a parameterless data-less contract (or a zero-input handler whose
            // input slot is the NoInput sentinel). Fabricate `new TIn()` instead
            // of deserializing: the descriptor declared no payload, so the runtime never asks a
            // serializer to materialize this type.
            var fabricateInput = j.InputPayloadFormatName == "none";

            sb.AppendLine(
                $"    public static object DeserializeInput_{suffix}(global::Acta.IJobPayloadSerializer serializer, global::Acta.JobPayload payload) =>"
            );
            if (fabricateInput)
            {
                sb.AppendLine($"        new {inputTypeName}();");
            }
            else
            {
                sb.AppendLine($"        serializer.Deserialize<{inputTypeName}>(payload)!;");
            }
            sb.AppendLine();

            if (j.OutputType is not null)
            {
                var outputTypeName = DisplayName(j.OutputType);
                sb.AppendLine(
                    $"    public static global::Acta.JobPayload SerializeOutput_{suffix}(global::Acta.IJobPayloadSerializer serializer, object? value) =>"
                );
                sb.AppendLine($"        serializer.Serialize<{outputTypeName}>(({outputTypeName})value!);");
                sb.AppendLine();
            }

            if (!j.Schedules.IsDefaultOrEmpty && j.InputPayloadFormatName != "none")
            {
                sb.AppendLine(
                    $"    public static global::Acta.JobPayload SerializeInput_{suffix}(global::Acta.IJobPayloadSerializer serializer, object value) =>"
                );
                sb.AppendLine($"        serializer.Serialize<{inputTypeName}>(({inputTypeName})value);");
                sb.AppendLine();
            }

            sb.AppendLine(
                $"    public static async global::System.Threading.Tasks.ValueTask<global::Acta.JobHandlerOutput> Invoke_{suffix}("
            );
            sb.AppendLine(
                "        global::System.IServiceProvider attemptServices, object request, global::Acta.JobContext context, global::System.Threading.CancellationToken ct)"
            );
            sb.AppendLine("    {");
            EmitInvokerBody(sb, j);
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        sb.AppendLine("}");
    }

    internal static void EmitInvokerBody(StringBuilder sb, DiscoveredJob j)
    {
        var handlerType = DisplayName(j.HandlerType!);

        // Zero-input handlers (j.InputType is null) take no request parameter: the runtime still
        // passes the fabricated NoInput sentinel as `request`, but the handler signature omits it.
        var args = new List<string>();
        if (j.TakesArguments)
        {
            sb.AppendLine($"        var typedRequest = ({j.ArgumentsTypeName})request;");
            args.AddRange(j.InputParameters.Select(p => $"typedRequest.{GeneratorText.EscapeIdentifier(p.Name)}"));
        }
        else if (j.InputType is not null)
        {
            sb.AppendLine($"        var typedRequest = ({DisplayName(j.InputType)})request;");
            args.Add("typedRequest");
        }
        if (j.RequiresJobContext)
        {
            args.Add("context");
        }
        if (j.RequiresCancellationToken)
        {
            args.Add("ct");
        }
        var argList = string.Join(", ", args);

        // Static handlers call the type directly. An instance handler registered in the per-attempt
        // scope is used as resolved and left to DI; otherwise the invoker constructs it from that scope
        // and owns it like an `await using` local: disposed on every exit, DisposeAsync first, and a
        // throwing dispose fails the attempt as any handler exception does.
        var method = GeneratorText.EscapeIdentifier(j.MethodName);
        string target;
        if (j.IsStaticMethod)
        {
            target = $"{handlerType}.{method}({argList})";
        }
        else
        {
            var construct =
                $"global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<{handlerType}>(attemptServices)";
            sb.AppendLine($"        var registered = ({handlerType}?)attemptServices.GetService(typeof({handlerType}));");
            if (DisposeStatement(j.HandlerType!) is { } dispose)
            {
                sb.AppendLine($"        {dispose} var owned = registered is null ? {construct} : null;");
                sb.AppendLine("        var handler = registered ?? owned!;");
            }
            else
            {
                sb.AppendLine($"        var handler = registered ?? {construct};");
            }
            target = $"handler.{method}({argList})";
        }

        // Three axes determine the body: is the handler async, does it return a T (vs void), and
        // does the descriptor propagate that T (hasResult). Voids stay synchronous and must
        // satisfy the ValueTask<T> invoker contract via an explicit `await ValueTask.CompletedTask`.
        // Async-no-result includes the "Task<T>-with-parameterless-T" collapse: the Task is still
        // awaited so side-effects/exceptions complete; the boxed empty value is discarded.
        var hasResult = j.OutputType is not null;
        var isAsync =
            j.InvocationKind
            is JobInvocationKind.Task
                or JobInvocationKind.TaskOfT
                or JobInvocationKind.ValueTask
                or JobInvocationKind.ValueTaskOfT;
        var returnsT = j.InvocationKind is JobInvocationKind.SyncOfT or JobInvocationKind.TaskOfT or JobInvocationKind.ValueTaskOfT;

        if (isAsync)
        {
            if (hasResult)
            {
                sb.AppendLine($"        var result = await {target};");
                sb.AppendLine("        return new global::Acta.JobHandlerOutput(HasResult: true, Result: result);");
            }
            else
            {
                sb.AppendLine($"        await {target};");
                sb.AppendLine("        return new global::Acta.JobHandlerOutput(HasResult: false, Result: null);");
            }
        }
        else
        {
            if (hasResult)
            {
                sb.AppendLine($"        var result = {target};");
            }
            else if (returnsT)
            {
                sb.AppendLine($"        _ = {target};");
            }
            else
            {
                sb.AppendLine($"        {target};");
            }
            sb.AppendLine("        await global::System.Threading.Tasks.ValueTask.CompletedTask;");
            var resultClause = hasResult ? "HasResult: true, Result: result" : "HasResult: false, Result: null";
            sb.AppendLine($"        return new global::Acta.JobHandlerOutput({resultClause});");
        }
    }

    /// <summary>
    /// The statement that disposes a constructed handler of this type, or null when it has no disposal. A value
    /// type is never disposed: its owned copy would not be the one the handler ran on.
    /// </summary>
    private static string? DisposeStatement(INamedTypeSymbol handlerType) =>
        !handlerType.IsReferenceType ? null
        : handlerType.AllInterfaces.Any(i => i.ToDisplayString() == "System.IAsyncDisposable") ? "await using"
        : handlerType.AllInterfaces.Any(i => i.SpecialType == SpecialType.System_IDisposable) ? "using"
        : null;

    /// <summary>The global-qualified type name; the format writes a keyword segment with its <c>@</c>.</summary>
    internal static string DisplayName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>
    /// <see cref="DisplayName"/> with a reference type's nullable annotation, since an argument record's member may be null.
    /// </summary>
    private static string ArgumentTypeName(ITypeSymbol type) =>
        type.ToDisplayString(
            SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
                SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier
            )
        );

    /// <summary>
    /// A zero-input handler has no TIn; its descriptor InputType slot is the framework NoInput
    /// sentinel so the runtime keeps a non-null input type for hashing, registration, and dispatch.
    /// A handler taking several parameters takes its argument record.
    /// </summary>
    internal static string InputTypeExpr(DiscoveredJob j) =>
        j.ArgumentsTypeName ?? (j.InputType is null ? "global::Acta.NoInput" : DisplayName(j.InputType));

    /// <summary>
    /// Job name (kebab) -&gt; C# identifier: capitalize the first letter of each alphanumeric run,
    /// drop separators. "hello" -&gt; "Hello", "send-mail" -&gt; "SendMail", "sys.alerts" -&gt; "SysAlerts".
    /// </summary>
    internal static string PascalCase(string jobName)
    {
        var sb = new StringBuilder(jobName.Length);
        var upcoming = true;
        foreach (var c in jobName)
        {
            if (!char.IsLetterOrDigit(c))
            {
                upcoming = true;
                continue;
            }
            sb.Append(upcoming ? char.ToUpperInvariant(c) : c);
            upcoming = false;
        }
        return sb.ToString();
    }

    internal static string PayloadFormatExpression(string name, IReadOnlyDictionary<string, byte> customFormatById) =>
        name switch
        {
            "none" => "global::Acta.JobPayloadFormat.None",
            "json" => "global::Acta.JobPayloadFormat.Json",
            "bytes" => "global::Acta.JobPayloadFormat.Bytes",
            _ when customFormatById.TryGetValue(name, out var id) => $"global::Acta.JobPayloadFormat.Custom({id}, \"{name}\")",
            // ACTA0132 rejects an unknown name and excludes the job before emit.
            _ => throw new InvalidOperationException($"Payload format '{name}' reached emit unvalidated."),
        };
}
