WITH batch AS (
    SELECT * FROM unnest(
        @p_d_definition_name, @p_d_job_priority_code, @p_d_max_attempts, @p_d_concurrency_limit,
        @p_d_rate_limit, @p_d_rate_name,
        @p_d_backoff,
        @p_d_execution_timeout, @p_d_deadline_seconds, @p_d_deadline_behavior, @p_d_job_retention,
        @p_d_input_type_name, @p_d_result_type_name,
        @p_d_input_format_id, @p_d_input_format_name, @p_d_result_format_id, @p_d_result_format_name,
        @p_d_event_recording_code, @p_d_alert_profile_code, @p_d_firing_failure_policy_code, @p_d_scheduled_delivery_code,
        @p_d_default_input_format_id, @p_d_default_input,
        @p_d_tenant_requirement,
        @p_d_alert_channel_name, @p_d_runbook_url, @p_d_display_name, @p_d_description, @p_d_definition_hash,
        @p_d_lane_name
    ) AS b(definition_name, job_priority_code, max_attempts, concurrency_limit,
        rate_limit, rate_name,
        backoff,
        execution_timeout_seconds, deadline_seconds,
        deadline_behavior_code, retention_seconds,
        input_type_name, result_type_name,
        input_format_id, input_format_name, result_format_id, result_format_name,
        event_recording_code, alert_profile_code, firing_failure_policy_code, scheduled_delivery_code,
        default_input_format_id, default_input,
        tenant_requirement_code,
        alert_channel_name, runbook_url, display_name, description, definition_hash, lane_name)
),
upserted AS (
    INSERT INTO {{schema}}.definitions (
        namespace_id,
        definition_name,
        definition_status_code,
        input_type_name,
        result_type_name,
        input_format_id,
        input_format_name,
        result_format_id,
        result_format_name,
        job_priority_code,
        max_attempts,
        concurrency_limit,
        rate_limit,
        rate_name,
        lane_name,
        backoff,
        execution_timeout_seconds,
        deadline_seconds,
        deadline_behavior_code,
        retention_seconds,
        event_recording_code,
        alert_profile_code,
        firing_failure_policy_code,
        scheduled_delivery_code,
        default_input_format_id,
        default_input,
        tenant_requirement_code,
        alert_channel_name,
        runbook_url,
        display_name,
        description,
        definition_hash,
        created_at_utc,
        modified_at_utc,
        version)
    SELECT
        @p_namespace_id,
        b.definition_name,
        10 /* DefinitionStatusCode.Active */,
        b.input_type_name,
        b.result_type_name,
        b.input_format_id,
        b.input_format_name,
        b.result_format_id,
        b.result_format_name,
        b.job_priority_code,
        b.max_attempts,
        b.concurrency_limit,
        b.rate_limit,
        b.rate_name,
        b.lane_name,
        b.backoff,
        b.execution_timeout_seconds,
        b.deadline_seconds,
        b.deadline_behavior_code,
        b.retention_seconds,
        b.event_recording_code,
        b.alert_profile_code,
        b.firing_failure_policy_code,
        b.scheduled_delivery_code,
        b.default_input_format_id,
        b.default_input,
        b.tenant_requirement_code,
        b.alert_channel_name,
        b.runbook_url,
        b.display_name,
        b.description,
        b.definition_hash,
        statement_timestamp(),
        statement_timestamp(),
        0
    FROM batch b
    ON CONFLICT (namespace_id, definition_name) DO UPDATE SET
        definition_status_code = 10 /* DefinitionStatusCode.Active */,
        input_type_name = EXCLUDED.input_type_name,
        result_type_name = EXCLUDED.result_type_name,
        input_format_id = EXCLUDED.input_format_id,
        input_format_name = EXCLUDED.input_format_name,
        result_format_id = EXCLUDED.result_format_id,
        result_format_name = EXCLUDED.result_format_name,
        job_priority_code = EXCLUDED.job_priority_code,
        max_attempts = EXCLUDED.max_attempts,
        concurrency_limit = EXCLUDED.concurrency_limit,
        rate_limit = EXCLUDED.rate_limit,
        rate_name = EXCLUDED.rate_name,
        lane_name = EXCLUDED.lane_name,
        backoff = EXCLUDED.backoff,
        execution_timeout_seconds = EXCLUDED.execution_timeout_seconds,
        deadline_seconds = EXCLUDED.deadline_seconds,
        deadline_behavior_code = EXCLUDED.deadline_behavior_code,
        retention_seconds = EXCLUDED.retention_seconds,
        event_recording_code = EXCLUDED.event_recording_code,
        alert_profile_code = EXCLUDED.alert_profile_code,
        firing_failure_policy_code = EXCLUDED.firing_failure_policy_code,
        scheduled_delivery_code = EXCLUDED.scheduled_delivery_code,
        default_input_format_id = EXCLUDED.default_input_format_id,
        default_input = EXCLUDED.default_input,
        tenant_requirement_code = EXCLUDED.tenant_requirement_code,
        alert_channel_name = EXCLUDED.alert_channel_name,
        runbook_url = EXCLUDED.runbook_url,
        display_name = EXCLUDED.display_name,
        description = EXCLUDED.description,
        definition_hash = EXCLUDED.definition_hash,
        -- The statement's time, not the transaction's: inside a deploy's transaction now() is from before the namespace
        -- lock was granted, and a stamp older than one a worker has seen would not make it reload.
        modified_at_utc = statement_timestamp(),
        version = {{schema}}.definitions.version + 1
    -- An unchanged Active row is left as it is: version and modified_at_utc stay, so no operator CAS fails and no
    -- worker reloads.
    WHERE
        {{schema}}.definitions.definition_status_code <> 10 /* DefinitionStatusCode.Active */
        OR {{schema}}.definitions.definition_hash IS DISTINCT FROM EXCLUDED.definition_hash
    RETURNING definitions.definition_name, definitions.definition_id
)
SELECT u.definition_name AS def_name, u.definition_id AS def_id FROM upserted u
UNION ALL
SELECT b.definition_name AS def_name, jd.definition_id AS def_id
FROM batch b
INNER JOIN {{schema}}.definitions jd
    ON jd.namespace_id = @p_namespace_id AND jd.definition_name = b.definition_name
WHERE NOT EXISTS (SELECT 1 FROM upserted u WHERE u.definition_name = b.definition_name);
